ROOT = Path(__file__).resolve().parents[1]


def choose(child, index):
    for _ in range(index):
        child.send("\x1b[B")
    child.send("\r")


def pause(child):
    child.expect_exact("Presione una tecla")
    child.send("\r")


def start(data_dir):
    child = pexpect.spawn("dotnet", ["run", "--project", "Project-C.csproj", "--no-build"],
                          cwd=str(ROOT), encoding="utf-8", timeout=20, dimensions=(40, 140),
                          env={**os.environ, "TERM": "xterm-256color",
                               "MYSHARPVENTURE_DATA_DIR": data_dir})
    child.logfile_read = io.StringIO()
    return child


def menu(child):
    child.expect_exact("¿Qué querés hacer?")
    child.expect_exact("Salir")


def stash_menu(child):
    child.expect_exact("¿Qué querés hacer con el stash?")
    child.expect_exact("Volver a preparación")


def finish(child):
    child.expect(pexpect.EOF)
    child.close()
    assert child.exitstatus == 0


