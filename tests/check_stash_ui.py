with tempfile.TemporaryDirectory(prefix="mysharp-stash-",
                                 dir="/tmp/opencode" if Path("/tmp/opencode").is_dir() else None) as data_dir:
    check(data_dir)
    check_overweight(data_dir)
    invalid_dir = Path(data_dir) / "invalida"
    invalid_dir.mkdir()
    invalid_file = invalid_dir / "game.db"
    invalid_file.write_bytes(b"conservar datos previos")
    rejected = start(str(invalid_dir))
    try:
        rejected.expect_exact("No se pudo abrir la base de datos")
        rejected.expect(pexpect.EOF)
        rejected.close()
        assert rejected.exitstatus == 1
        assert invalid_file.read_bytes() == b"conservar datos previos"
    finally:
        if rejected.isalive():
            rejected.close(force=True)
